let currentLang = "fr";

function setLang(lang) {
  currentLang = lang;
  const t = translations[lang];

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (t[key] && el.tagName !== "INPUT" && el.tagName !== "TEXTAREA") {
      el.textContent = t[key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.dataset.i18nPlaceholder;
    if (t[key]) {
      el.placeholder = t[key];
    }
  });

  document.querySelector(".lang-fr").classList.toggle("active-lang", lang === "fr");
  document.querySelector(".lang-en").classList.toggle("active-lang", lang === "en");
  document.documentElement.lang = lang === "fr" ? "fr" : "en";

  const bioBtn = document.getElementById("bioReadMore");
  if (bioBtn) {
    const bioBox = bioBtn.closest(".bio-text");
    bioBtn.textContent = bioBox && !bioBox.classList.contains("collapsed") ? t.bio_read_less : t.bio_read_more;
  }
}

document.getElementById("langToggle").addEventListener("click", () => {
  const next = currentLang === "fr" ? "en" : "fr";
  setLang(next);
});

// Background ambience (Solitude)
const ambienceToggle = document.getElementById("ambienceToggle");
if (ambienceToggle) {
  const ambienceAudio = new Audio("audio/Nouveau dossier/atmo_steh.mp3");
  ambienceAudio.loop = true;
  ambienceAudio.preload = "auto";
  const SEG_START = 55;
  const SEG_END = 150;
  let ambienceStarted = false;

  function startAmbience() {
    ambienceStarted = true;
    ambienceAudio.play().catch(() => {});
    ambienceToggle.classList.add("active");
  }

  ambienceAudio.addEventListener("loadedmetadata", () => {
    ambienceAudio.currentTime = SEG_START;
  });
  ambienceAudio.addEventListener("timeupdate", () => {
    if (ambienceAudio.currentTime >= SEG_END) {
      ambienceAudio.currentTime = SEG_START;
    }
  });

  ambienceToggle.addEventListener("click", () => {
    if (ambienceAudio.paused) {
      startAmbience();
    } else {
      ambienceAudio.pause();
      ambienceToggle.classList.remove("active");
    }
  });

  window.addEventListener("pointerdown", startAmbience, { once: true });
  window.addEventListener("keydown", startAmbience, { once: true });

  startAmbience();
}

